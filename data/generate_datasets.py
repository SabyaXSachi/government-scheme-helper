def write_csv(path, fieldnames, rows) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    # Quality checks before writing anything.
    names = {s["scheme_name"] for s in SCHEMES}
    assert len(names) == len(SCHEMES), "duplicate scheme names"
    assert len(SCHEMES) == 48, f"expected 48 schemes, got {len(SCHEMES)}"
    for cat in CATEGORIES:
        n = sum(1 for s in SCHEMES if s["category"] == cat)
        assert n == 12, f"{cat}: expected 12 schemes, got {n}"
        n_cards = sum(1 for _, c in FLASHCARDS if c == cat)
        assert n_cards == 50, f"{cat}: expected 50 flashcards, got {n_cards}"
    assert len(FLASHCARDS) == 200, f"expected 200 flashcards, got {len(FLASHCARDS)}"
    assert len(set(t for t, _ in FLASHCARDS)) == 200, "duplicate flashcard text"
    assert len(EVALUATION) == 50, f"expected 50 evaluation questions, got {len(EVALUATION)}"
    for _, expected_scheme, cat in EVALUATION:
        assert expected_scheme in names, f"eval question references unknown scheme: {expected_scheme}"
        assert cat in CATEGORIES, f"unknown category in eval set: {cat}"

    write_csv(DATA_DIR / "schemes.csv",
              ["scheme_name", "category", "eligibility", "benefits",
               "how_to_apply", "documents_required", "source_url", "last_verified"],
              SCHEMES)
    write_csv(DATA_DIR / "flashcards.csv", ["text", "category"],
              [{"text": t, "category": c} for t, c in FLASHCARDS])
    write_csv(DATA_DIR / "evaluation_set.csv",
              ["question", "expected_scheme", "expected_category"],
              [{"question": q, "expected_scheme": s, "expected_category": c}
               for q, s, c in EVALUATION])

    print(f"Wrote {len(SCHEMES)} schemes, {len(FLASHCARDS)} flashcards, "
          f"{len(EVALUATION)} evaluation questions -> {DATA_DIR}")
    print("All quality checks passed: 12 schemes and 50 flashcards per category, "
          "no duplicates, every eval question references a corpus scheme.")


if __name__ == "__main__":
    main()
